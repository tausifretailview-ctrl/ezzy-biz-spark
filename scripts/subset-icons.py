"""Rebuilds the Phosphor duotone icon subset used by the marketing pages.

The pages draw icons with <i className="ph-duotone ph-NAME">. Instead of loading the full
Phosphor stylesheet (230 KB) and font (160 KB) from a CDN, the build ships only the icons
the pages use: src/pages/fonts/phosphor-duotone.woff2 plus the rules in src/pages/icons.css.

After adding or changing an icon name in src/pages, run:

    pip install fonttools brotli
    python3 scripts/subset-icons.py

It finds every "ph-..." name under src/pages, downloads @phosphor-icons/web with npm pack,
and rewrites the two files. An icon that is not in the subset renders as nothing.
"""
import pathlib
import re
import subprocess
import sys
import tarfile
import tempfile

from fontTools import subset

VERSION = "2.1.1"
ROOT = pathlib.Path(__file__).resolve().parent.parent
PAGES = ROOT / "src" / "pages"
OUT_CSS = PAGES / "icons.css"
OUT_FONT = PAGES / "fonts" / "phosphor-duotone.woff2"

names = set()
for path in PAGES.rglob("*.ts*"):
    names.update(re.findall(r"\bph-[a-z0-9]+(?:-[a-z0-9]+)*\b", path.read_text(encoding="utf-8")))
names.discard("ph-duotone")

with tempfile.TemporaryDirectory() as tmp:
    subprocess.run(["npm", "pack", f"@phosphor-icons/web@{VERSION}", "--silent"], cwd=tmp, check=True, stdout=subprocess.DEVNULL)
    with tarfile.open(next(pathlib.Path(tmp).glob("*.tgz"))) as tar:
        tar.extractall(tmp, filter="data")
    src = pathlib.Path(tmp) / "package" / "src" / "duotone"
    css = (src / "style.css").read_text(encoding="utf-8")

    rules, codepoints, missing = [], set(), []
    for name in sorted(names):
        found = re.findall(r"(\.ph-duotone\.%s:(?:before|after)\s*\{[^}]*\})" % re.escape(name), css)
        if not found:
            missing.append(name)
        rules += found
        for block in found:
            codepoints.update(int(cp, 16) for cp in re.findall(r'content:\s*"\\([0-9a-f]+)"', block))
    if missing:
        sys.exit("Not a Phosphor icon: " + ", ".join(missing))

    opts = subset.Options()
    opts.flavor = "woff2"
    opts.layout_features = []
    font = subset.load_font(str(src / "Phosphor-Duotone.woff2"), opts)
    subsetter = subset.Subsetter(opts)
    subsetter.populate(unicodes=sorted(codepoints))
    subsetter.subset(font)
    OUT_FONT.parent.mkdir(exist_ok=True)
    subset.save_font(font, str(OUT_FONT), opts)

OUT_CSS.write_text(
    f"""/* Generated by scripts/subset-icons.py from @phosphor-icons/web {VERSION} (MIT). Do not edit by hand:
   add the icon name in src/pages, then run the script. */

@font-face {{
  font-family: "Phosphor-Duotone";
  src: url("./fonts/phosphor-duotone.woff2") format("woff2");
  font-weight: normal;
  font-style: normal;
  font-display: block;
}}

.ph-duotone {{
  font-family: "Phosphor-Duotone" !important;
  speak: never;
  font-style: normal;
  font-weight: normal;
  font-variant: normal;
  text-transform: none;
  line-height: 1;
  -webkit-font-smoothing: antialiased;
  -moz-osx-font-smoothing: grayscale;
}}

"""
    + "\n".join(rules)
    + "\n",
    encoding="utf-8",
)
print(f"{len(names)} icons, {len(codepoints)} glyphs, font {OUT_FONT.stat().st_size // 1024} KB")
